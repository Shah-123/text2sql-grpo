"""Where did GRPO help, and where does the model still fail? Compares two eval runs question by question.

    python error_analysis.py        # writes outputs/eval/error_analysis.md

Failed queries are re-run to read the SQLite error message and the shape of the wrong results.
"""
import json
import re
from collections import Counter
from math import comb
from pathlib import Path

import sql_rewards
from sql_rewards import execute

SPLITS = {"Spider dev": "spider_dev", "BIRD Mini-Dev": "bird_minidev"}
RUNS = {"base": "base", "GRPO": "grpo_zero"}
LABELS = ["correct", "wrong_result", "exec_error", "no_sql", "gold_error"]
_n = lambda pat, s: len(re.findall(pat, s, re.I))
FEATURES = {  # features of the gold query; Spider has no difficulty labels, so these stand in for them
    "no JOIN": lambda s: _n(r"\bJOIN\b", s) == 0,
    "1 JOIN": lambda s: _n(r"\bJOIN\b", s) == 1,
    "2+ JOINs": lambda s: _n(r"\bJOIN\b", s) >= 2,
    "GROUP BY": lambda s: _n(r"\bGROUP\s+BY\b", s) > 0,
    "ORDER BY": lambda s: _n(r"\bORDER\s+BY\b", s) > 0,
    "subquery or set op": lambda s: _n(r"\bSELECT\b", s) > 1,
}
ERRORS = [("no such column", "unknown column"), ("no such table", "unknown table"), ("ambiguous", "ambiguous column"),
          ("interrupted", "timeout (>30 s)"), ("no such function", "unknown function"), ("only SELECT", "not a SELECT"),
          ("syntax error", "syntax error"), ("incomplete input", "syntax error"), ("misuse of aggregate", "aggregate misuse"),
          ("one statement at a time", "several statements"), ("UNION do not have", "UNION column mismatch")]


def error_type(r):
    try:
        execute(r["db_path"], r["pred_sql"])
        return "ran on re-check"
    except Exception as e:
        return next((name for key, name in ERRORS if key in str(e)), "other")


def wrong_type(r):
    try:
        pred, gold = execute(r["db_path"], r["pred_sql"]), execute(r["db_path"], r["gold_sql"])
    except Exception:
        return "timeout on re-check"
    if not pred:
        return "returns no rows"
    if gold and len(pred[0]) != len(gold[0]):
        return "different number of columns"
    return "right columns, wrong values"


def pct(oks):
    return f"{100 * sum(oks) / len(oks):.1f}%" if oks else "-"


def table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
                     + ["| " + " | ".join(map(str, row)) + " |" for row in rows])


def compare(name, runs, typer, label):
    counts = {m: Counter(typer(r) for r in rows if r["label"] == label) for m, rows in runs.items()}
    kinds = sorted(set().union(*counts.values()), key=lambda k: -sum(c[k] for c in counts.values()))
    return [f"### {name}", "", table(["type", *runs], [(k, *(c[k] for c in counts.values())) for k in kinds]), ""]


def example(title, r_base, r_grpo):
    return [f"**{title}** ({r_base['db_id']}): {r_base['question']}", "", "```sql",
            f"-- gold\n{r_base['gold_sql']}", f"-- base ({r_base['label']})\n{r_base['pred_sql']}",
            f"-- GRPO ({r_grpo['label']})\n{r_grpo['pred_sql']}", "```", ""]


sql_rewards.TIMEOUT = 30.0  # same as eval.py
out = ["# Error analysis: Qwen2.5-Coder-3B, base vs. GRPO", "",
       "Generated by `error_analysis.py` from the per-question outputs of `eval.py`. "
       "Base answers were parsed leniently, GRPO answers strictly (`<sql>` tags required).", ""]
for title, split in SPLITS.items():
    runs = {m: [json.loads(line) for line in open(f"outputs/eval/{run}_{split}.jsonl", encoding="utf-8")]
            for m, run in RUNS.items()}
    base, grpo = runs.values()
    assert [r["question"] for r in base] == [r["question"] for r in grpo], "eval files are not in the same order"
    ok = {m: [r["label"] == "correct" for r in rows] for m, rows in runs.items()}
    fixed = [i for i, (b, g) in enumerate(zip(*ok.values())) if g and not b]
    broke = [i for i, (b, g) in enumerate(zip(*ok.values())) if b and not g]
    n = len(fixed) + len(broke)
    p = min(1.0, 2 * sum(comb(n, k) for k in range(min(len(fixed), len(broke)) + 1)) / 2 ** n)  # exact McNemar

    out += [f"## {title} ({len(base)} questions)", "",
            f"Accuracy {pct(ok['base'])} → {pct(ok['GRPO'])}. GRPO fixed {len(fixed)} questions and broke "
            f"{len(broke)} (net {len(fixed) - len(broke):+d}); exact McNemar p = {p:.3f}.", "",
            "### Outcomes", "",
            table(["outcome", *runs], [(lab, *(sum(r["label"] == lab for r in rows) for rows in runs.values()))
                                       for lab in LABELS if any(r["label"] == lab for r in base + grpo)]), "",
            "### Accuracy by query type", ""]
    tags = [{f"gold has {k}" for k, f in FEATURES.items() if f(r["gold_sql"])} | {f"difficulty: {r['difficulty']}"}
            for r in base]
    rows = []
    for g in [f"gold has {k}" for k in FEATURES] + [f"difficulty: {d}" for d in ("simple", "moderate", "challenging")]:
        idx = [i for i, t in enumerate(tags) if g in t]
        if not idx:
            continue
        b, t = [ok["base"][i] for i in idx], [ok["GRPO"][i] for i in idx]
        rows.append((g, len(idx), pct(b), pct(t), f"{100 * (sum(t) - sum(b)) / len(idx):+.1f}"))
    out += [table(["questions", "n", "base", "GRPO", "change"], rows), ""]
    out += compare("Execution errors", runs, error_type, "exec_error")
    out += compare("Wrong results", runs, wrong_type, "wrong_result")
    short = lambda idx: min(idx, key=lambda i: len(base[i]["gold_sql"]))
    out += ["### Examples", ""] + example("Fixed by GRPO", base[short(fixed)], grpo[short(fixed)]) \
        + example("Broken by GRPO", base[short(broke)], grpo[short(broke)])
    print(f"{title}: done", flush=True)

Path("outputs/eval/error_analysis.md").write_text("\n".join(out), encoding="utf-8")
print("wrote outputs/eval/error_analysis.md")
